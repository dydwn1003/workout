# A key written twice silently keeps only the last one (this once turned
# the coaching report's title into the report-a-post title): refuse.
_keys = re.findall(r'^ "(\w+)":', open(__file__, encoding="utf-8").read(), re.M)
_dups = sorted({k for k in _keys if _keys.count(k) > 1})
if _dups:
    raise SystemExit("duplicate l10n keys: " + ", ".join(_dups))

def placeholders(s):
    # Keep order of first appearance; generated method args follow it.
    return list(dict.fromkeys(re.findall(r"\{(\w+)\}", s)))

def write(lang, idx):
    out = {"@@locale": lang}
    for k, v in S.items():
        out[k] = v[idx]
        if idx == 0:
            ph = placeholders(v[0])
            if ph:
                out["@" + k] = {"placeholders": {p: {"type": "String"} for p in ph}}
    path = os.path.join(os.path.dirname(__file__), "..", "lib", "l10n", f"app_{lang}.arb")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
        f.write("\n")

for k, v in S.items():
    assert sorted(placeholders(v[0])) == sorted(placeholders(v[1])), k
write("ko", 0)
write("en", 1)
print(f"{len(S)} strings written")
